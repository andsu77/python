# OPERADORES RELACIONAIS
# Eles comparam valores e retornam True (verdadeiro) ou False (falso)
# Igual a ==
# Diferente de !=
# Maior que >
# Menor que <
# Maior ou igual a >=
# Menor ou igual a <= 
# IMPORTANTE:
# = atribui um valor: a = 10
# == compara dois valores: a == b




print(10>20);
print(200<10);
print(200>100);
print(200>=200);
print(200<300);

nome = "anderson";
nome2 = "josé";
nome3= "anderson";

print(nome == nome2);
print(nome == nome3);

print(10 != 10)

#operadores lógicos
#and so é verdadeiro se todos forem verdadeiros 
